function t(key){ const lang = (Store.data && Store.data.settings.appLang) || 'pt'; const v = (I18N[lang]||I18N.pt)[key]; return v!==undefined ? v : (I18N.pt[key]!==undefined ? I18N.pt[key] : key); }
function tf(key, vars){
  let s = t(key);
  Object.keys(vars||{}).forEach(k=>{ s = s.split('{'+k+'}').join(vars[k]); });
  return s;
}
function applyI18N(){
  document.documentElement.lang = (Store.data.settings.appLang==='en') ? 'en' : 'pt-BR';
  document.querySelectorAll('[data-i18n]').forEach(el=>{ el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-aria]').forEach(el=>{ el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
